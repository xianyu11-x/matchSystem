func (p *ScalarProgram) evalStringPredicate(node scalarNode, lookup Lookup, path string, remaining int) (bool, error) {
	leftPath := path + ".left"
	if node.kind == kindStringsEmpty {
		leftPath = path + ".values"
	}
	left, err := p.evalStrings(node.value, lookup, leftPath, remaining-1)
	if err != nil {
		return false, err
	}
	left = uniqueStrings(left)
	switch node.kind {
	case kindStringsEmpty:
		return len(left) == 0, nil
	case kindStringsContains:
		return containsString(left, node.name), nil
	}
	right, err := p.evalStrings(node.right, lookup, path+".right", remaining-1)
	if err != nil {
		return false, err
	}
	right = uniqueStrings(right)
	switch node.kind {
	case kindStringsEqual:
		return equalStrings(left, right), nil
	case kindStringsNotEqual:
		return !equalStrings(left, right), nil
	case kindStringsContainsAny, kindStringsIntersects:
		return intersectsStrings(left, right), nil
	case kindStringsContainsAll:
		return containsAllStrings(left, right), nil
	default:
		return false, evaluateError(path, "TYPE_MISMATCH", "scalar node %s does not produce bool", node.kind)
	}
}

func (p *ScalarProgram) evalUint64Predicate(node scalarNode, lookup Lookup, path string, remaining int) (bool, error) {
	leftPath := path + ".left"
	if node.kind == kindUint64sEmpty {
		leftPath = path + ".values"
	}
	left, err := p.evalUint64s(node.value, lookup, leftPath, remaining-1)
	if err != nil {
		return false, err
	}
	left = uniqueUint64s(left)
	switch node.kind {
	case kindUint64sEmpty:
		return len(left) == 0, nil
	case kindUint64sContains:
		return containsUint64(left, node.uint64s[0]), nil
	}
	right, err := p.evalUint64s(node.right, lookup, path+".right", remaining-1)
	if err != nil {
		return false, err
	}
	right = uniqueUint64s(right)
	switch node.kind {
	case kindUint64sEqual:
		return equalUint64s(left, right), nil
	case kindUint64sNotEqual:
		return !equalUint64s(left, right), nil
	case kindUint64sContainsAny, kindUint64sIntersects:
		return intersectsUint64s(left, right), nil
	case kindUint64sContainsAll:
		return containsAllUint64s(left, right), nil
	default:
		return false, evaluateError(path, "TYPE_MISMATCH", "scalar node %s does not produce bool", node.kind)
	}
}

func compareInt64(kind scalarKind, left, right int64) bool {
	switch kind {
	case kindInt64Equal:
		return left == right
	case kindInt64NotEqual:
		return left != right
	case kindInt64Less:
		return left < right
	case kindInt64LessOrEqual:
		return left <= right
	case kindInt64Greater:
		return left > right
	case kindInt64GreaterOrEqual:
		return left >= right
	default:
		return false
	}
}

func saturatingAdd(left, right int64) int64 {
	if right > 0 && left > int64(^uint64(0)>>1)-right {
		return int64(^uint64(0) >> 1)
	}
	if right < 0 && left < -int64(^uint64(0)>>1)-1-right {
		return -int64(^uint64(0)>>1) - 1
	}
	return left + right
}

func saturatingSub(left, right int64) int64 {
	if right > 0 && left < -int64(^uint64(0)>>1)-1+right {
		return -int64(^uint64(0)>>1) - 1
	}
	if right < 0 && left > int64(^uint64(0)>>1)+right {
		return int64(^uint64(0) >> 1)
	}
	return left - right
}

func uniqueStrings(values []string) []string {
	if len(values) == 0 {
		return nil
	}
	out := append([]string(nil), values...)
	sort.Strings(out)
	write := 1
	for read := 1; read < len(out); read++ {
		if out[read] != out[write-1] {
			out[write] = out[read]
			write++
		}
	}
	return out[:write]
}

func uniqueUint64s(values []uint64) []uint64 {
	if len(values) == 0 {
		return nil
	}
	out := append([]uint64(nil), values...)
	sort.Slice(out, func(i, j int) bool { return out[i] < out[j] })
	write := 1
	for read := 1; read < len(out); read++ {
		if out[read] != out[write-1] {
			out[write] = out[read]
			write++
		}
	}
	return out[:write]
}

func equalStrings(left, right []string) bool {
	if len(left) != len(right) {
		return false
	}
	for index := range left {
		if left[index] != right[index] {
			return false
		}
	}
	return true
}

func containsString(values []string, target string) bool {
	index := sort.SearchStrings(values, target)
	return index < len(values) && values[index] == target
}

func intersectsStrings(left, right []string) bool {
	leftIndex, rightIndex := 0, 0
	for leftIndex < len(left) && rightIndex < len(right) {
		switch {
		case left[leftIndex] < right[rightIndex]:
			leftIndex++
		case left[leftIndex] > right[rightIndex]:
			rightIndex++
		default:
			return true
		}
	}
	return false
}

func containsAllStrings(values, needles []string) bool {
	for _, needle := range needles {
		if !containsString(values, needle) {
			return false
		}
	}
	return true
}

func equalUint64s(left, right []uint64) bool {
	if len(left) != len(right) {
		return false
	}
	for index := range left {
		if left[index] != right[index] {
			return false
		}
	}
	return true
}

func containsUint64(values []uint64, target uint64) bool {
	index := sort.Search(len(values), func(index int) bool { return values[index] >= target })
	return index < len(values) && values[index] == target
}

func intersectsUint64s(left, right []uint64) bool {
	leftIndex, rightIndex := 0, 0
	for leftIndex < len(left) && rightIndex < len(right) {
		switch {
		case left[leftIndex] < right[rightIndex]:
			leftIndex++
		case left[leftIndex] > right[rightIndex]:
			rightIndex++
		default:
			return true
		}
	}
	return false
}

func containsAllUint64s(values, needles []uint64) bool {
	for _, needle := range needles {
		if !containsUint64(values, needle) {
			return false
		}
	}
	return true
}

func itoa(value int) string {
	// Child indexes are bounded by JSONLimits.MaxChildren. Avoid fmt on the
	// successful evaluator path while keeping the error path readable.
	if value == 0 {
		return "0"
	}
	var buf [20]byte
	index := len(buf)
	for value > 0 {
		index--
		buf[index] = byte('0' + value%10)
		value /= 10
	}
	return string(buf[index:])
}
